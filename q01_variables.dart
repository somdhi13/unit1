void main() {
  // Declaring variables using var, final, and const
  var name = 'Rahul Sharma';
  final rollNumber = 42;
  const city = 'Ahmedabad';

  // Printing using string interpolation
  print('Name: $name');
  print('Roll Number: $rollNumber');
  print('City: $city');
  print('Summary: $name (Roll No: $rollNumber) lives in $city.');
}
